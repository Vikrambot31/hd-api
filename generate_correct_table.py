def create_sequential_gates():
    """
    Создает логически правильное распределение:
    - 64 ворота
    - Каждый занимает 5.625° (360/64)
    - Последовательно от 0° к 360°
    """

    print("📊 Генерирую последовательное распределение ворот...")

    lookup_table = []
    gate_size = 360.0 / 64  # 5.625° на ворота

    for gate_num in range(1, 65):
        # Начало и конец диапазона для этого Ворот
        lon_start = (gate_num - 1) * gate_size
        lon_end = gate_num * gate_size

        # Каждый Ворота разделен на 6 линий × 6 тонов = 36 записей
        # Каждая запись занимает gate_size / 36 градусов
        step = gate_size / 36

        for i in range(36):
            lon = lon_start + i * step
            line = (i // 6) + 1  # Линии 1-6
            tone = (i % 6) + 1   # Тоны 1-6
            color = (i // 6) + 1  # Цвет совпадает с линией

            # Формат: [longitude, gate, line, color, tone]
            lookup_table.append([lon, gate_num, line, color, tone])

    return lookup_table

